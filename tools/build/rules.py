                  "[[ -n \"${FAIL:-}\" ]] && exit 1\n"
                  "echo %s >> build.log\n%s\n"
                  "if [[ -n \"${EDIT:-}\" ]]; then echo edited >> \"$EDIT\"; fi\n"
