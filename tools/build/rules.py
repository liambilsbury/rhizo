def make_fixture(tmp):
    """create a fixture repo with the Makefile, stamps.py and rules.py"""
    for rel in ("Makefile", "tools/build/stamps.py", "tools/build/rules.py"):
        os.makedirs(os.path.dirname(os.path.join(tmp, rel)) or tmp, exist_ok=True)
        shutil.copy(os.path.join(ROOT, rel), os.path.join(tmp, rel))
    files = {
        "tools/build/artifacts.tsv": FIXTURE_TSV,
        "tools/build/g1/a.sh": FIXTURE_SCRIPT % ("a", "a", "mkdir -p var/share && echo a > var/share/a"),
        "tools/build/g2/b.sh": FIXTURE_SCRIPT % ("b", "b", "mkdir -p var/share && echo b > var/share/b1 && echo b > var/share/b2\n"
                                                "python3 tools/build/stamps.py stamp b1 b2"),
        "tools/build/g1/t.sh": FIXTURE_SCRIPT % ("t", "t", "mkdir -p toolchain/t"),
        "src/a.c": "a1\n", "src/b.c": "b1\n", "src/t.c": "t1\n",
        ".rhizo-inputs.tsv": "", "debian/changelog": "rhizo (0.0.1) noble; urgency=medium\n",
    }
    for rel, body in files.items():
        path = os.path.join(tmp, rel)
        os.makedirs(os.path.dirname(path) or tmp, exist_ok=True)
        with open(path, "w") as f:
            f.write(body)
        if rel.endswith(".sh"):
            os.chmod(path, 0o755)
    subprocess.run([sys.executable, os.path.join(tmp, "tools/build/rules.py")], check=True, cwd=tmp)


def make(tmp, *args, env=None):
    """run make -s in tmp and return the CompletedProcess"""
    e = dict(os.environ, **(env or {}))
    e.pop("MAKEFLAGS", None)
    return subprocess.run(["make", "-s"] + list(args), cwd=tmp, capture_output=True, text=True, env=e)


def built(tmp):
    """return the words in tmp/build.log"""
    try:
        with open(os.path.join(tmp, "build.log")) as f:
            return f.read().split()
    except OSError:
        return []


def selftest():
    """run the Makefile and rules.py selftest cases"""
    fail = 0

    def expect(cond, ok, bad):
        """print ok or FAIL for cond and set fail"""
        nonlocal fail
        if cond:
            print("ok   " + ok)
        else:
            print("FAIL " + bad)
            fail = 1

    tmp = tempfile.mkdtemp(prefix="rules-selftest-")
    try:
        make_fixture(tmp)
        r = make(tmp, "payload")
        expect(r.stderr == "", "make payload stderr == \"\"",
               "make payload stderr == \"\" (%r)" % r.stderr)
        expect(r.returncode == 0 and built(tmp) == ["a", "b"],
               "make payload exits 0 and builds a b",
               "make payload exits 0 and builds a b (rc=%d log=%s err=%s)" % (r.returncode, built(tmp), r.stderr))
        r = make(tmp, "-q", "payload")
        expect(r.returncode == 0, "make -q payload exits 0",
               "make -q payload exits 0 (rc=%d)" % r.returncode)
        make(tmp, "payload")
        expect(built(tmp) == ["a", "b"], "second make payload builds nothing",
               "second make payload builds nothing (log=%s)" % built(tmp))
        os.utime(os.path.join(tmp, "src/a.c"))
        r = make(tmp, "-q", "payload")
        expect(r.returncode == 0, "make -q payload after os.utime(src/a.c) exits 0",
               "make -q payload after os.utime(src/a.c) exits 0 (rc=%d)" % r.returncode)
        with open(os.path.join(tmp, "src/b.c"), "w") as f:
            f.write("b2\n")
        r = make(tmp, "-n", "payload")
        expect("g2/b.sh" in r.stdout and "g1/a.sh" not in r.stdout,
               "make -n payload after a write to src/b.c prints g2/b.sh and no g1/a.sh",
               "make -n payload after a write to src/b.c prints g2/b.sh and no g1/a.sh (%r)" % r.stdout)
        make(tmp, "payload")
        expect(built(tmp) == ["a", "b", "b"], "make payload after a write to src/b.c builds b",
               "make payload after a write to src/b.c builds b (log=%s)" % built(tmp))
        with open(os.path.join(tmp, "src/a.c"), "w") as f:
            f.write("a2\n")
        make(tmp, "payload")
        r = make(tmp, "-q", "payload")
        expect(built(tmp) == ["a", "b", "b", "a", "b"] and r.returncode == 0,
               "make payload after a write to src/a.c builds a b, then make -q payload exits 0",
               "make payload after a write to src/a.c builds a b, then make -q payload exits 0 (log=%s rc=%d)"
               % (built(tmp), r.returncode))
        with open(os.path.join(tmp, "src/a.c"), "w") as f:
            f.write("a3\n")
        make(tmp, "a")
        r = make(tmp, "-q", "payload")
        r2 = make(tmp, "-n", "payload")
        expect(built(tmp)[5:] == ["a"] and r.returncode != 0 and "g2/b.sh" in r2.stdout and "g1/a.sh" not in r2.stdout,
               "make a builds a, make -q payload exits 1, make -n payload prints g2/b.sh",
               "make a builds a, make -q payload exits 1, make -n payload prints g2/b.sh (log=%s rc=%d make -n=%r)"
               % (built(tmp), r.returncode, r2.stdout))
        make(tmp, "payload")
        r = make(tmp, "-q", "payload")
        expect(built(tmp)[6:] == ["b"] and r.returncode == 0,
               "make payload after make a builds b, then make -q payload exits 0",
               "make payload after make a builds b, then make -q payload exits 0 (log=%s rc=%d)"
               % (built(tmp)[6:], r.returncode))
        copy = tmp + "-copy"
        shutil.copytree(tmp, copy)
        try:
            for dirpath, _, filenames in os.walk(copy):
                for fn in filenames:
                    os.utime(os.path.join(dirpath, fn))
            r = make(copy, "-q", "payload")
            expect(r.returncode == 0, "make -q payload in a copy after os.utime on each file exits 0",
                   "make -q payload in a copy after os.utime on each file exits 0 (rc=%d)" % r.returncode)
        finally:
            shutil.rmtree(copy, ignore_errors=True)
        with open(os.path.join(tmp, "src/b.c"), "w") as f:
            f.write("b3\n")
        r = make(tmp, "payload", env={"FAIL": "1"})
        r2 = make(tmp, "-q", "payload")
        expect(r.returncode != 0 and r2.returncode != 0, "make payload with FAIL=1 and make -q payload exit 1",
               "make payload with FAIL=1 and make -q payload exit 1 (make rc=%d make -q rc=%d)"
               % (r.returncode, r2.returncode))
        make(tmp, "b1")
        expect(built(tmp)[-1] == "b", "make b1 builds b",
               "make b1 builds b (log=%s)" % built(tmp))
        with open(os.path.join(tmp, "src/b.c"), "w") as f:
            f.write("b4\n")
        r = make(tmp, "payload", env={"EDIT": "src/b.c"})
        r2 = make(tmp, "-q", "payload")
        expect(r.returncode != 0 and "b1" in r.stderr and "sources changed during the build" in r.stderr and r2.returncode != 0,
               "make payload with EDIT=src/b.c exits 1 with b1 in stderr, then make -q payload exits 1",
               "make payload with EDIT=src/b.c exits 1 with b1 in stderr, then make -q payload exits 1"
               " (make rc=%d err=%r make -q rc=%d)" % (r.returncode, r.stderr, r2.returncode))
        n = len(built(tmp))
        make(tmp, "payload")
        r2 = make(tmp, "-q", "payload")
        expect(built(tmp)[n:] == ["b"] and r2.returncode == 0,
               "make payload after the EDIT run builds b, then make -q payload exits 0",
               "make payload after the EDIT run builds b, then make -q payload exits 0 (log=%s rc=%d)"
               % (built(tmp)[n:], r2.returncode))
        os.remove(os.path.join(tmp, "var/share/a"))
        r = make(tmp, "payload", env={"FAIL_AFTER": "1"})
        r2 = make(tmp, "-q", "payload")
        expect(r.returncode != 0 and os.path.exists(os.path.join(tmp, "var/share/a")) and r2.returncode != 0,
               "make payload with FAIL_AFTER=1 writes var/share/a and exits 1, then make -q payload exits 1",
               "make payload with FAIL_AFTER=1 writes var/share/a and exits 1, then make -q payload exits 1"
               " (make rc=%d make -q rc=%d)" % (r.returncode, r2.returncode))
        n = len(built(tmp))
        make(tmp, "payload")
        r2 = make(tmp, "-q", "payload")
        expect(built(tmp)[n:n + 1] == ["a"] and r2.returncode == 0,
               "make payload after the FAIL_AFTER run builds a, then make -q payload exits 0",
               "make payload after the FAIL_AFTER run builds a, then make -q payload exits 0 (log=%s rc=%d)"
               % (built(tmp)[n:], r2.returncode))
        os.remove(os.path.join(tmp, "tools/build/rules.mk"))
        r = make(tmp, "-q", "payload")
        with open(os.path.join(tmp, "tools/build/rules.mk")) as f:
            remade = f.read()
        expect(r.returncode == 0 and remade == render(load_stamps().entries(os.path.join(tmp, "tools/build/artifacts.tsv"))),
               "make -q payload without tools/build/rules.mk writes render(entries) and exits 0",
               "make -q payload without tools/build/rules.mk writes render(entries) and exits 0 (rc=%d err=%r)"
               % (r.returncode, r.stderr))
        r = make(tmp, "g1")
        expect(built(tmp)[-1] == "t" and os.path.exists(os.path.join(tmp, "toolchain/t.srchash")),
               "make g1 builds t and writes toolchain/t.srchash",
               "make g1 builds t and writes toolchain/t.srchash (rc=%d log=%s)" % (r.returncode, built(tmp)))
        os.remove(os.path.join(tmp, ".rhizo-inputs.tsv"))
        os.remove(os.path.join(tmp, "var/share/a.srchash"))
        r = make(tmp, "a")
        expect(r.returncode != 0 and "no .rhizo-inputs.tsv" in r.stderr,
               "make a without .rhizo-inputs.tsv exits 1 with 'no .rhizo-inputs.tsv' in stderr",
               "make a without .rhizo-inputs.tsv exits 1 with 'no .rhizo-inputs.tsv' in stderr (rc=%d err=%r)"
               % (r.returncode, r.stderr))
        with open(os.path.join(tmp, ".rhizo-inputs.tsv"), "w"):
            pass
        with open(os.path.join(tmp, "tools/build/artifacts.tsv"), "a") as f:
            f.write("broken row\n")
        r = make(tmp, "-q", "payload")
        expect(r.returncode != 0 and "stamps.py" in r.stderr,
               "make -q payload with a broken artifacts.tsv row exits 1 with stamps.py in stderr",
               "make -q payload with a broken artifacts.tsv row exits 1 with stamps.py in stderr (rc=%d err=%r)"
               % (r.returncode, r.stderr))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    stamps = load_stamps()
    rows = stamps.entries(path=None, text=FIXTURE_TSV.replace("\tpayload\ta\n", "\tpayload\t-\n", 1))
    tmp = tempfile.mkdtemp(prefix="rules-order-")
    try:
        os.makedirs(os.path.join(tmp, "tools/build/g1"))
        os.makedirs(os.path.join(tmp, "tools/build/g2"))
        for rel, body in (("tools/build/g1/a.sh", "tools/build/hal/hal.sh x\n"),
                          ("tools/build/g2/b.sh", "source tools/build/toolchain/android-sdk.sh\n"),
                          ("tools/build/g1/t.sh", "echo t\n")):
            with open(os.path.join(tmp, rel), "w") as f:
                f.write(body)
        got = order_findings(rows, tmp)
        expect(any(g.startswith("a ") and "gsi_libs" in g for g in got),
               "order_findings() has an a finding with gsi_libs",
               "order_findings() has an a finding with gsi_libs (%s)" % got)
        expect(any(g.startswith("b1 ") and "aapt2" in g for g in got),
               "order_findings() has a b1 finding with aapt2",
               "order_findings() has a b1 finding with aapt2 (%s)" % got)
        expect(not any(g.startswith("toolchain/t ") for g in got),
               "order_findings() has no toolchain/t finding",
               "order_findings() has no toolchain/t finding (%s)" % got)
        loop = stamps.entries(path=None, text="x\ttools/build/g1/t.sh\tsrc\ttest\ty\ny\ttools/build/g1/t.sh\tsrc\ttest\tx\n")
        expect(any("loop" in g for g in order_findings(loop, tmp)), "order_findings() has a build order loop x -> y -> x",
               "order_findings() has a build order loop x -> y -> x")
        shutil.copy(os.path.join(ROOT, "Makefile"), os.path.join(tmp, "Makefile"))
        os.makedirs(os.path.join(tmp, "tools/build/help"))
        with open(os.path.join(tmp, "tools/build/help/x.sh"), "w") as f:
            f.write("echo x\n")

        def clashes(*named):
            """return check() findings for (name, build) rows"""
            rows = [stamps.Entry(n, b, ["src"], "test", []) for n, b in named]
            return check(rows, tmp)

        plain = "tools/build/g1/t.sh"
        for name in ("payload", "help", "setup", "container", "shell"):
            got = clashes((name, plain))
            expect(len(got) == 1 and name in got[0] and "Makefile" in got[0],
                   "check() has one finding for row %s with Makefile" % name,
                   "check() has one finding for row %s with Makefile (%s)" % (name, got))
        got = clashes(("env-deb", plain))
        expect(len(got) == 1 and "env-deb" in got[0] and "env-%" in got[0],
               "check() has one finding for row env-deb with env-%",
               "check() has one finding for row env-deb with env-% (%s)" % got)
        got = clashes(("x", "tools/build/help/x.sh"))
        expect(len(got) == 1 and "tools/build/help/" in got[0] and "Makefile" in got[0],
               "check() has one finding for tools/build/help/ with Makefile",
               "check() has one finding for tools/build/help/ with Makefile (%s)" % got)
        got = clashes(("g1", plain))
        expect(len(got) == 1 and "g1" in got[0] and "group" in got[0],
               "check() has one finding for row g1 with group",
               "check() has one finding for row g1 with group (%s)" % got)
        for ch in "%:#$=; \t":
            name = "a%sb" % ch
            got = clashes((name, plain))
            expect(len(got) == 1 and repr(name) in got[0],
                   "check() has one finding for a row with %r" % ch,
                   "check() has one finding for row %r (%s)" % (name, got))
        got = clashes(("gfx_hal/libc++_shared.so", plain), ("rel/a15/x-y_z.apk", plain), ("x", plain))
        expect(got == [], "check() == [] for gfx_hal/libc++_shared.so, rel/a15/x-y_z.apk and x",
               "check() == [] for gfx_hal/libc++_shared.so, rel/a15/x-y_z.apk and x (%s)" % got)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print("%s rules.py --selftest" % ("FAIL" if fail else "ok"))
    return fail


def main(argv):
    """run --selftest, --check or help, or write rules.mk"""
    if argv[1:] == ["--selftest"]:
        return selftest()
    entries = load_stamps().entries()
    if argv[1:] == ["--check"]:
        bad = check(entries)
        for b in bad:
            print("FAIL " + b)
        if bad:
            return 1
        print("ok rules.py --check")
        return 0
    if argv[1:] == ["help"]:
        sys.stdout.write(help_text(entries))
        return 0
    if argv[1:]:
        print("rules.py [--check|--selftest|help]", file=sys.stderr)
        return 2
    write(entries)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
