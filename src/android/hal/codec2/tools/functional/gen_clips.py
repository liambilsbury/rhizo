#!/usr/bin/env python3
"""write the launch probe's functional clips and frame MD5s to clips_data.cpp"""
import argparse
import hashlib
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "clips_data.cpp")
WIDTH, HEIGHT, FRAMES = 128, 96, 4
SOURCE = f"testsrc2=size={WIDTH}x{HEIGHT}:rate=30"

CLIPS = [
    ("avc-high-8bit", "kAvc", "VAProfileH264High", 8, "kAnnexB",
     ["-c:v", "libx264", "-profile:v", "high", "-pix_fmt", "yuv420p", "-preset", "medium",
      "-x264-params", "keyint=30:min-keyint=30:scenecut=0:bframes=0:ref=2:cqm=flat:log-level=error", "-f", "h264"]),
    ("hevc-main-8bit", "kHevc", "VAProfileHEVCMain", 8, "kAnnexB",
     ["-c:v", "libx265", "-profile:v", "main", "-pix_fmt", "yuv420p",
      "-x265-params", "keyint=30:min-keyint=30:scenecut=0:bframes=0:ref=2:scaling-list=off:log-level=error",
      "-f", "hevc"]),
    ("hevc-main10-10bit", "kHevc", "VAProfileHEVCMain10", 10, "kAnnexB",
     ["-c:v", "libx265", "-profile:v", "main10", "-pix_fmt", "yuv420p10le",
      "-x265-params", "keyint=30:min-keyint=30:scenecut=0:bframes=0:ref=2:scaling-list=off:log-level=error",
      "-f", "hevc"]),
    ("vp9-p0-8bit", "kVp9", "VAProfileVP9Profile0", 8, "kIvf",
     ["-c:v", "libvpx-vp9", "-profile:v", "0", "-pix_fmt", "yuv420p", "-b:v", "300k", "-g", "30",
      "-auto-alt-ref", "0", "-lag-in-frames", "0", "-deadline", "good", "-cpu-used", "4", "-f", "ivf"]),
    ("vp9-p2-10bit", "kVp9", "VAProfileVP9Profile2", 10, "kIvf",
     ["-c:v", "libvpx-vp9", "-profile:v", "2", "-pix_fmt", "yuv420p10le", "-b:v", "300k", "-g", "30",
      "-auto-alt-ref", "0", "-lag-in-frames", "0", "-deadline", "good", "-cpu-used", "4", "-f", "ivf"]),
    ("av1-main-8bit", "kAv1", "VAProfileAV1Profile0", 8, "kIvf",
     ["-c:v", "libaom-av1", "-pix_fmt", "yuv420p", "-b:v", "300k", "-g", "30", "-lag-in-frames", "0",
      "-usage", "good", "-cpu-used", "6", "-denoise-noise-level", "0", "-f", "ivf"]),
    ("av1-main-10bit", "kAv1", "VAProfileAV1Profile0", 10, "kIvf",
     ["-c:v", "libaom-av1", "-pix_fmt", "yuv420p10le", "-b:v", "300k", "-g", "30", "-lag-in-frames", "0",
      "-usage", "good", "-cpu-used", "6", "-denoise-noise-level", "0", "-f", "ivf"]),
]


def run(argv):
    """run a command and return its stdout"""
    r = subprocess.run(argv, capture_output=True)
    if r.returncode != 0:
        sys.exit(f"gen_clips: {' '.join(argv)} failed: {r.stderr.decode(errors='replace')[-800:]}")
    return r.stdout


def make(name, depth, args, tmp):
    """encode a clip and return its bytes and frame MD5s"""
    path = os.path.join(tmp, name)
    run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", SOURCE, "-frames:v", str(FRAMES)]
        + args + [path])
    data = open(path, "rb").read()
    types = run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "frame=pict_type",
                 "-of", "csv=p=0", path]).decode().split()
    types = [t.split(",")[0] for t in types]
    if types != ["I"] + ["P"] * (FRAMES - 1):
        sys.exit(f"gen_clips: {name} decodes as {types}, want I then {FRAMES - 1} P frames")
    pix = "yuv420p10le" if depth == 10 else "yuv420p"
    raw = run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", path, "-f", "rawvideo", "-pix_fmt", pix, "-"])
    frame = WIDTH * HEIGHT * 3 // 2 * (2 if depth == 10 else 1)
    if len(raw) != frame * FRAMES:
        sys.exit(f"gen_clips: {name} decodes to {len(raw)} bytes, want {FRAMES} frames of {frame}")
    return data, [hashlib.md5(raw[i * frame:(i + 1) * frame]).hexdigest() for i in range(FRAMES)]


def ident(name):
    """return the C++ identifier stem for a clip name"""
    return "k" + "".join(p.capitalize() for p in name.replace("-", " ").split())


def render(results, versions):
    """return the clips_data.cpp text"""
    out = ["// generated by gen_clips.py; do not edit",
           f"// made with: {versions}",
           "",
           '#include "tools/functional/clips.h"',
           "",
           "namespace rhizo::c2va {",
           "",
           "namespace {",
           ""]
    for name, codec, profile, depth, framing, data, md5s in results:
        stem = ident(name)
        out.append(f"// {name}: {len(data)} bytes")
        out.append(f"const uint8_t {stem}Data[] = {{")
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        out.append("};")
        out.append(f"const char* const {stem}Md5[] = {{" + ", ".join(f'"{m}"' for m in md5s) + "};")
        out.append("")
    out.append("}  // namespace")
    out.append("")
    out.append("const FunctionalClip kFunctionalClips[] = {")
    for name, codec, profile, depth, framing, data, md5s in results:
        stem = ident(name)
        out.append(f'    {{"{name}", Codec::{codec}, {profile}, {depth}, {WIDTH}, {HEIGHT}, ClipFraming::{framing}, '
                   f"{stem}Data, sizeof({stem}Data), {len(md5s)}, {stem}Md5}},")
    out.append("};")
    out.append("const size_t kFunctionalClipCount = sizeof(kFunctionalClips) / sizeof(kFunctionalClips[0]);")
    out.append("")
    out.append("}  // namespace rhizo::c2va")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    ver = run(["ffmpeg", "-hide_banner", "-version"]).decode().splitlines()[0]
    results = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, codec, profile, depth, framing, args in CLIPS:
            data, md5s = make(name, depth, args, tmp)
            results.append((name, codec, profile, depth, framing, data, md5s))
            print(f"gen_clips: {name}: {len(data)} bytes, md5 {md5s[0][:8]}..", file=sys.stderr)
    text = render(results, ver)
    if a.check:
        same = os.path.exists(a.out) and open(a.out).read() == text
        print("gen_clips: %s %s" % (a.out, "matches" if same else "differs (encoder versions move bytes; the "
                                    "committed file stands as long as its own digests check)"))
        return 0 if same else 1
    with open(a.out, "w") as f:
        f.write(text)
    print(f"gen_clips: wrote {a.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
